"""
Deterministic guard for auto-generated dependency version-bump PRs.

Why this exists
---------------
batch_coding._open_files_pr lets a "version bump" title (the
``name old -> new (pypi|npm release)`` format dependency_releases.py emits)
edit EXISTING files, on the reasoning that a bump has "no context to
hallucinate". That reasoning only holds if the model's output is checked: the
model is asked for whole files and nothing verified that what came back was
actually a version bump. Observed 2026-10-28 (PRs #462-#467):

  * pydantic_core / weasyprint bumps added unrelated modules, or files
    identical to ones already on main (no dependency touched at all);
  * a react-collapsible bump added a markdown note only;
  * a tailwindcss bump added a patch file with a placeholder version, and a
    second tailwindcss bump OVERWROTE the root package.json (renamed the
    project, deleted the log4brains ADR scripts and devDependency).

and each was logged as ``success: true``.

What it enforces
----------------
For a version-bump title, every proposed file must be an existing dependency
manifest, and the only lines that differ from the file on disk may be lines
that name the bumped package, where swapping the new version string back for
the old one reproduces the original line exactly. Anything else (new files,
unrelated files, no-op rewrites, added/removed lines, lines for other
packages) is rejected with a reason. The guard never edits content; it only
accepts or rejects what the model produced.

Lockfiles are intentionally not accepted: they must be regenerated by the
package manager, not rewritten by a model.
"""

from __future__ import annotations

import re
from collections.abc import Callable, Mapping
from dataclasses import dataclass

_TITLE_RE = re.compile(r"^(\S+) (\S+) -> (\S+) \((pypi|npm) release\)$")

_NPM_MANIFESTS = re.compile(r"(^|/)package\.json$")
_PYPI_MANIFESTS = re.compile(
    r"(^|/)(requirements[^/]*\.(txt|in)|constraints[^/]*\.txt|pyproject\.toml)$"
)


@dataclass(frozen=True)
class BumpSpec:
    name: str
    old: str
    new: str
    ecosystem: str


def parse_title(title: str) -> BumpSpec | None:
    """Parse ``name old -> new (eco release)``; None if it is not that format."""
    m = _TITLE_RE.match((title or "").strip())
    if not m:
        return None
    name, old, new, eco = m.groups()
    if old == new:
        return None
    return BumpSpec(name=name, old=old, new=new, ecosystem=eco)


def _norm(text: str) -> str:
    """PEP 503-style normalisation so pydantic_core == pydantic-core."""
    return re.sub(r"[-_.]+", "-", text.lower())


def _names_package(line: str, name: str) -> bool:
    """True if ``line`` refers to exactly this package (not a longer name that
    merely contains it, e.g. pydantic vs pydantic_core or react vs
    @radix-ui/react-collapsible)."""
    pattern = r"(?<![\w@/-])" + re.escape(_norm(name)) + r"(?![\w-])"
    return re.search(pattern, _norm(line)) is not None


def _manifest_ok(spec: BumpSpec, rel_path: str) -> bool:
    rx = _NPM_MANIFESTS if spec.ecosystem == "npm" else _PYPI_MANIFESTS
    return bool(rx.search(rel_path))


def check_file(spec: BumpSpec, rel_path: str, new_content: str, old_content: str | None) -> str | None:
    """Return a rejection reason, or None if this file is a clean bump."""
    if old_content is None:
        return "creates a new file; a version bump may only edit an existing dependency manifest"
    if not _manifest_ok(spec, rel_path):
        return f"not a {spec.ecosystem} dependency manifest"
    if new_content == old_content:
        return "identical to the file on disk (no change)"

    old_lines = old_content.splitlines()
    new_lines = new_content.splitlines()
    if len(old_lines) != len(new_lines):
        return (
            f"line count changed ({len(old_lines)} -> {len(new_lines)}); "
            "a version bump only edits lines in place"
        )

    changed = 0
    for i, (old_line, new_line) in enumerate(zip(old_lines, new_lines), start=1):
        if old_line == new_line:
            continue
        changed += 1
        if not _names_package(old_line, spec.name) or not _names_package(new_line, spec.name):
            return f"line {i} changed but does not name {spec.name}"
        if spec.old not in old_line or spec.new not in new_line:
            return f"line {i} does not move {spec.old} -> {spec.new}"
        if new_line.replace(spec.new, spec.old) != old_line:
            return f"line {i} changes more than the version string"
    if changed == 0:
        # Only trailing-newline / line-ending differences.
        return "differs from the file on disk only in whitespace or line endings"
    return None


def filter_version_bump_files(
    title: str,
    files: Mapping[str, str],
    read_existing: Callable[[str], str | None],
) -> tuple[dict[str, str], dict[str, str]]:
    """Split ``files`` into (accepted, rejected_with_reason) for a bump title.

    A title that does not parse as a version bump rejects everything: callers
    should only use this for titles already identified as bumps.
    """
    spec = parse_title(title)
    if spec is None:
        return {}, {rel: "title is not a version-bump title" for rel in files}
    accepted: dict[str, str] = {}
    rejected: dict[str, str] = {}
    for rel, content in files.items():
        reason = check_file(spec, rel, content, read_existing(rel))
        if reason is None:
            accepted[rel] = content
        else:
            rejected[rel] = reason
    return accepted, rejected
