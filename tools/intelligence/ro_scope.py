#!/usr/bin/env python3
"""Render the SELECT-only verification script for the read-only Supabase role from the single source of truth,
.claude/hooks/supabase_ro_scope.json.

  python tools/intelligence/ro_scope.py > tools/intelligence/ro_scope_verify.sql

Nothing here connects to a database. There is deliberately no migration: table-level read scope cannot be made database-enforced with the
access we hold (the `postgres` role cannot revoke the platform-granted pg_read_all_data membership; see tests/test_supabase_ro_access.py).
The verify script checks the parts that ARE database facts (read-only default, no write privileges, no executable SECURITY DEFINER
functions, permitted views depending only on permitted relations) and flags drift: new public relations missing from the scope lists, or the
platform changing the role. Run it after any GRANT, new SECURITY DEFINER function, new public table, or Supabase maintenance.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

CONFIG = Path(__file__).resolve().parents[2] / ".claude" / "hooks" / "supabase_ro_scope.json"
ROLE = "supabase_read_only_user"


def load() -> dict:
    return json.loads(CONFIG.read_text(encoding="utf-8"))


def _q(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def render_verify(cfg: dict | None = None, role: str = ROLE) -> str:
    cfg = cfg or load()
    permitted = ", ".join("('" + r + "')" for r in cfg["permitted_relations"])
    column_limited = ", ".join("('" + r + "')" for r in cfg.get("column_grants", {}))
    return f"""-- READ-ONLY verification of the read posture and scope drift of {role}. Generated by tools/intelligence/ro_scope.py. Expected value is on each row.
with permitted(name) as (values {permitted}),
col_limited(name) as (values {column_limited}),
public_rels as (select c.oid, c.relname from pg_class c where c.relnamespace = 'public'::regnamespace and c.relkind in ('r','v','m','p'))
select 'member_of_pg_read_all_data (platform-managed; table scope is application-level)' as check, pg_has_role('{role}', 'pg_read_all_data', 'member')::text as value, 'true (cannot be revoked by postgres); if false the scope is now database-enforced' as expected
union all
select 'member_of_pg_monitor (other sessions query text readable; the guard refuses those functions and views)', pg_has_role('{role}', 'pg_monitor', 'member')::text, 'true today' 
union all
select 'default_transaction_read_only', coalesce((select array_to_string(s.setconfig, ';') from pg_db_role_setting s where s.setrole = '{role}'::regrole), '(none)'), 'default_transaction_read_only=on'
union all
select 'public_relation_names', string_agg(r.relname, ',' order by r.relname), 'run: python tools/intelligence/ro_scope.py drift "<this value>" ; must print NEW: (none)'
from public_rels r
union all
select 'relations_with_effective_write_privileges', coalesce(string_agg(n.nspname || '.' || c.relname, ', ' order by c.relname), '(none)'), '(none)'
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where c.relkind in ('r','v','m','p','f') and n.nspname not in ('pg_catalog','information_schema','pg_toast')
  and (has_table_privilege('{role}', c.oid, 'INSERT,UPDATE,DELETE,TRUNCATE') or has_any_column_privilege('{role}', c.oid, 'INSERT,UPDATE'))
union all
select 'schemas_it_can_create_in', count(*)::text, '0'
from pg_namespace n where has_schema_privilege('{role}', n.oid, 'create') and n.nspname not like 'pg_%' and n.nspname <> 'information_schema'
union all
-- a SECURITY DEFINER function it can execute would run with its owner's rights and could read or write outside this scope
select 'secdef_functions_executable_non_system', coalesce(string_agg(n.nspname || '.' || p.proname, ', '), '(none)'), '(none)'
from pg_proc p join pg_namespace n on n.oid = p.pronamespace
where p.prosecdef and n.nspname not in ('pg_catalog','information_schema') and has_function_privilege('{role}', p.oid, 'execute')
union all
-- a view runs with its OWNER's privileges: every permitted view must depend only on permitted relations
select 'permitted_views_depending_on_unpermitted_relations',
  coalesce(string_agg(distinct v.relname || ' -> ' || d.relname, ', '), '(none)'), '(none)'
from pg_class v join permitted p on p.name = v.relname and v.relnamespace = 'public'::regnamespace and v.relkind in ('v','m')
join pg_rewrite rw on rw.ev_class = v.oid
join pg_depend dep on dep.objid = rw.oid and dep.classid = 'pg_rewrite'::regclass and dep.refclassid = 'pg_class'::regclass
join pg_class d on d.oid = dep.refobjid and d.relnamespace = 'public'::regnamespace and d.oid <> v.oid
where d.relname not in (select name from permitted);
"""


def drift(names_csv: str, cfg: dict | None = None) -> tuple[list[str], list[str]]:
    """Compare the relation names the database reports (the `public_relation_names` row) with the scope lists. Returns (new, gone)."""
    cfg = cfg or load()
    seen = {n.strip() for n in names_csv.split(",") if n.strip()}
    known = set(cfg["all_public_relations"])
    return sorted(seen - known), sorted(known - seen)


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "drift":
        new, gone = drift(sys.argv[2] if len(sys.argv) > 2 else sys.stdin.read())
        print("NEW (add to all_public_relations and decide permitted or not): " + (", ".join(new) or "(none)"))
        print("GONE (remove from the lists): " + (", ".join(gone) or "(none)"))
        sys.exit(1 if new else 0)
    sys.stdout.write(render_verify())
